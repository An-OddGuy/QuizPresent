// Generates js/env.js from environment variables (or a local .env file).
// Local:   node scripts/build-config.mjs
// Deploy:  run by .github/workflows/deploy.yml with GitHub Secrets as env vars.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

if (existsSync(".env")) {
  for (const line of readFileSync(".env", "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && process.env[m[1]] === undefined) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}
const need = ["FIREBASE_API_KEY", "FIREBASE_AUTH_DOMAIN", "FIREBASE_DATABASE_URL", "FIREBASE_PROJECT_ID", "FIREBASE_APP_ID"];
const missing = need.filter(k => !process.env[k]);
if (missing.length) { console.error("Missing env values: " + missing.join(", ")); process.exit(1); }

const ENV = {
  DEMO_BLE: (process.env.DEMO_BLE ?? "true") !== "false",
  firebase: {
    apiKey: process.env.FIREBASE_API_KEY, authDomain: process.env.FIREBASE_AUTH_DOMAIN,
    databaseURL: process.env.FIREBASE_DATABASE_URL, projectId: process.env.FIREBASE_PROJECT_ID, appId: process.env.FIREBASE_APP_ID
  }
};
writeFileSync("js/env.js", "// GENERATED by scripts/build-config.mjs. Do not edit or commit.\nexport const ENV = " + JSON.stringify(ENV, null, 2) + ";\n");
console.log("js/env.js written.");
